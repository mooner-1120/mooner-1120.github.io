import { RaceId } from './data';

export interface ChoiceOption {
  label: string;
  lines: string[];
  flags?: string[];
  /** 고를 수 있는 조건 (특수: MEM4 = 기억 4개 이상, TRUE_END = 진 엔딩 조건) */
  req?: string;
  reqText?: string;
}

export type Objective =
  | { k: 'talk'; npc: string; text: string }
  | { k: 'kill'; enemy: string | string[]; n: number; text: string }
  | { k: 'flag'; flag: string; text: string }
  | { k: 'collect'; mat: string; n: number; text: string }
  | { k: 'choice'; npc: string; text: string; prompt: string; options: ChoiceOption[] };

type ByRace = Partial<Record<RaceId, string[]>>;

export interface QuestDef {
  id: string;
  name: string;
  main?: boolean;
  chapter?: number;
  giver: string;
  race?: RaceId;
  requires?: string;
  offer: string[];
  offerByRace?: ByRace;
  stages: Objective[];
  done: string[];
  doneByRace?: ByRace;
  /** 대화·선택 단계를 마칠 때 나오는 대사 */
  talks?: Record<number, string[]>;
  talksByRace?: Record<number, ByRace>;
  /** 단계를 마치면 켜지는 플래그 */
  stageFlags?: Record<number, string>;
  reward: { xp: number; gold: number; soul?: number; items?: [string, number][]; mats?: [string, number][]; removeMats?: string[]; equip?: string; rarity?: number; flag?: string; flags?: string[] };
  next?: string;
  autoAccept?: boolean;
  chapterClear?: number;
}

