export function greeting(npc: string, race: RaceId, flags: Record<string, unknown>): string {
  const list = GREET[npc];
  if (!list) return '...';
  for (const g of list) {
    if (g.race && !g.race.includes(race)) continue;
    if (g.when && !flags[g.when]) continue;
    if (g.unless && flags[g.unless]) continue;
    return g.lines[(Math.random() * g.lines.length) | 0];
  }
  return '...';
}

